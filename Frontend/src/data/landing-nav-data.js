function quickLinksForRadiologyGroup(group) {
    const links = [];
    for (const item of group.items) {
        const label = item.name.length > 30 ? `${item.name.slice(0, 28)}…` : item.name;
        if (links.length >= 4)
            break;
        links.push(label);
    }
    return links;
}
